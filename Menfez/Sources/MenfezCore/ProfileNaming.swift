// ProfileNaming.swift — a human name and a country for any WireGuard config.
//
// WHY THIS EXISTS
// The picker used to derive everything from the filename, which works only when
// a provider follows a rigid pattern. A user-supplied file called
// "server.conf" produced a blank row, and a city called "RO1" is not something
// anyone recognises.
//
// So there are three sources, tried in order of trustworthiness:
//
//   1. A name the config carries itself — a `# Name = ...` or `# Description =
//      ...` comment, or `# friendly_name = ...`. Providers that generate files
//      from a panel usually include one, and the user chose that name.
//   2. A city/region in the filename, which is what the big providers produce.
//   3. The filename stem, cleaned up, as a last resort.
//
// The country code is separate and has its own ladder:
//
//   1. A two-letter code in the filename (`VPN-RO1-...`), already parsed by
//      `WireGuardProfiles`.
//   2. The exit IP, looked up once and cached, when the filename says nothing.
//      This costs a network request, so the caller decides when to pay it —
//      the picker pays on open, never on the five-second refresh.
//
// Nothing here performs I/O. The country lookup is a separate call so a unit
// test can exercise naming without a network.

import Foundation

public enum ProfileNaming {

    /// Config comment keys that carry a display name, lowercased.
    ///
    /// These are what real panels emit: wg-quick writes `# Name =` in some
    /// generators, WireGuard's own `wg-quick save` writes none, and several
    /// hosted providers use `# Description =` or `# friendly_name =`.
    static let nameKeys = ["name", "description", "friendly_name", "friendlyname",
                           "server", "location", "city"]

    /// The name to show in the picker.
    ///
    /// - Parameters:
    ///   - stem: the profile's identifier, normally the filename without `.conf`.
    ///   - configText: the file's contents, or nil when it could not be read.
    ///     nil is not an error here: the caller still gets a usable name.
    public static func displayName(stem: String, configText: String?) -> String {
        if let text = configText, let named = nameFromComments(text) {
            return named
        }
        if let city = cityFromStem(stem) {
            return city
        }
        return tidy(stem)
    }

    /// A `# Key = value` comment, if the config has one the user would
    /// recognise. Only keys in `nameKeys` are considered, so a licence header
    /// or a "generated by" line is not mistaken for a server name.
    static func nameFromComments(_ text: String) -> String? {
        for rawLine in text.split(separator: "\n", omittingEmptySubsequences: true) {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            guard line.hasPrefix("#") else { continue }
            let body = line.dropFirst().trimmingCharacters(in: .whitespaces)

            // Split on the first '=' or ':' so "# Name: Amsterdam" works too.
            guard let separator = body.firstIndex(where: { $0 == "=" || $0 == ":" })
            else { continue }
            let key = body[..<separator]
                .trimmingCharacters(in: .whitespaces)
                .lowercased()
            let value = body[body.index(after: separator)...]
                .trimmingCharacters(in: .whitespaces)

            guard nameKeys.contains(key), !value.isEmpty, value.count <= 40 else {
                continue
            }
            // A value that looks like a URL or a key is not a display name.
            if value.contains("://") || value.contains("=") { continue }
            if value.allSatisfy({ $0.isHexDigit || $0 == "+" || $0 == "/" || $0 == "=" }) {
                continue
            }
            return value
        }
        return nil
    }

    /// "VPN-RO1-RO-229" -> "Romanya" (via the country name, not the code);
    /// "my-amsterdam-1" -> "Amsterdam".
    ///
    /// The ladder, in order:
    ///   1. a two-letter uppercase segment (a country code) is the most
    ///      trustworthy thing a provider filename carries;
    ///   2. otherwise a letters-plus-digits segment ("RO1");
    ///   3. otherwise the most descriptive word, which is the longest one.
    ///
    /// Threshold-of-two everywhere: a one-letter segment is a version marker,
    /// not a place, and a purely numeric segment is a server index.
    static func cityFromStem(_ stem: String) -> String? {
        let skip: Set<String> = ["conf", "wg", "vpn", "server", "free", "premium",
                                 "secure", "core", "p2p", "plus", "pro", "wal",
                                 "the", "my", "and"]
        let parts = stem.split(whereSeparator: { $0 == "-" || $0 == "_" })
            .map(String.init)
            .filter { $0.count >= 2 }

        // 1. A two-letter alphabetic segment is a country code. A code is not a
        //    name a person recognises ("RO" is not "Romanya"), so it is resolved
        //    through the country table. An unknown code falls through to the
        //    other rungs rather than showing bare letters.
        for part in parts where part.count == 2
            && part.allSatisfy({ $0.isLetter && $0.isASCII })
            && !skip.contains(part.lowercased()) {
            if let name = CountryNames.name(part.uppercased(), turkish: true) {
                return name
            }
            return part.uppercased()
        }

        // 2. Letters immediately followed by digits ("RO1", "AMS2").
        for part in parts {
            let letters = part.prefix { $0.isLetter }
            let digits = part.dropFirst(letters.count)
            guard letters.count >= 2, !digits.isEmpty,
                  digits.allSatisfy(\.isNumber) else { continue }
            if skip.contains(letters.lowercased()) { continue }
            return letters.count == 2 ? letters.uppercased() : letters.capitalized
        }

        // 3. The longest meaningful word, which in "my-office-vpn" is "office"
        //    and in "amsterdam-home" is "amsterdam".
        let words = parts.filter { part in
            !skip.contains(part.lowercased())
                && !part.allSatisfy(\.isNumber)
                && part.contains(where: \.isLetter)
        }
        guard let best = words.max(by: { $0.count < $1.count }), best.count >= 3
        else { return nil }
        return best.capitalized
    }

    /// Filename stem to something presentable: dashes and underscores become
    /// spaces, each word capitalised, long stems trimmed.
    static func tidy(_ stem: String) -> String {
        let words = stem
            .replacingOccurrences(of: "_", with: "-")
            .split(separator: "-")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            .map { $0.capitalized }
        let joined = words.joined(separator: " ")
        if joined.isEmpty { return stem }
        return joined.count > 40 ? String(joined.prefix(40)) : joined
    }

    /// Turn a two-letter code into a flag emoji.
    ///
    /// Regional indicator symbols are the ASCII letters offset into the
    /// U+1F1E6 block. Anything that is not exactly two letters returns nil, so
    /// a malformed country never renders as a broken glyph.
    public static func flag(_ code: String?) -> String? {
        guard let code, code.count == 2,
              code.allSatisfy({ $0.isASCII && $0.isLetter }) else { return nil }
        let base: UInt32 = 0x1F1E6
        var scalars = String.UnicodeScalarView()
        for character in code.uppercased().unicodeScalars {
            guard let scalar = UnicodeScalar(base + character.value - 65) else {
                return nil
            }
            scalars.append(scalar)
        }
        return String(scalars)
    }
}

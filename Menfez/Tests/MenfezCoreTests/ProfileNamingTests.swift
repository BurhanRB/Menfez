import XCTest
@testable import MenfezCore

/// The picker is the first thing a user sees, so a wrong or blank name there
/// reads as a broken app. These tests pin the naming ladder and the flag
/// conversion.
final class ProfileNamingTests: XCTestCase {

    // MARK: - Name from the config itself

    func testNameCommentWinsOverFilename() {
        let config = """
        # Name = Amsterdam Home
        [Interface]
        PrivateKey = aGVsbG8=
        """
        XCTAssertEqual(
            ProfileNaming.displayName(stem: "work", configText: config),
            "Amsterdam Home")
    }

    func testDescriptionAndColonFormsAreAccepted() {
        for comment in ["# Description = Tokyo", "# friendly_name = Tokyo",
                        "# Name: Tokyo", "# city = Tokyo", "# Server = Tokyo"] {
            let config = "\(comment)\n[Interface]\nPrivateKey = x\n"
            XCTAssertEqual(
                ProfileNaming.displayName(stem: "srv", configText: config),
                "Tokyo",
                "failed for \(comment)")
        }
    }

    /// A licence header or a generated-by line must not become the server name.
    func testUnrelatedCommentsAreIgnored() {
        let config = """
        # generated by some panel v2
        # URL = https://example.com/download
        # Key = aGVsbG8gd29ybGQ=
        [Interface]
        PrivateKey = x
        """
        let name = ProfileNaming.displayName(stem: "nl-350", configText: config)
        XCTAssertNotEqual(name, "https://example.com/download")
        XCTAssertNotEqual(name, "aGVsbG8gd29ybGQ=")
        XCTAssertEqual(name, "Hollanda",
                       "a bare country code is shown as the country's name, not as letters")
    }

    /// A very long value is a description, not a label.
    func testOverlongCommentValueIsRejected() {
        let long = String(repeating: "a", count: 80)
        let config = "# Name = \(long)\n[Interface]\n"
        XCTAssertNotEqual(
            ProfileNaming.displayName(stem: "tokyo-1", configText: config),
            long)
    }

    // MARK: - Name from the filename

    func testCityComesFromTheFilename() {
        XCTAssertEqual(ProfileNaming.displayName(stem: "VPN-RO1-RO-229", configText: nil),
                       "Romanya",
                       "a country code in the filename becomes the country name")
    }

    /// A filename with filler words yields the descriptive part, not the whole
    /// stem: "my_office_vpn" is the office server, not a server called
    /// "my office vpn".
    func testReadableFilenameYieldsTheDescriptiveWord() {
        XCTAssertEqual(ProfileNaming.displayName(stem: "my_office_vpn", configText: nil),
                       "Office")
    }

    /// With no filler to strip, the whole stem is presented tidily.
    func testPlainFilenameIsTidied() {
        XCTAssertEqual(ProfileNaming.displayName(stem: "amsterdam-home", configText: nil),
                       "Amsterdam")
    }

    /// A purely numeric or version-like stem must not turn into a "city".
    func testNumbersAreNotMistakenForPlaces() {
        let name = ProfileNaming.displayName(stem: "229", configText: nil)
        XCTAssertEqual(name, "229")
    }

    func testUnreadableConfigStillYieldsAName() {
        // `nil` means the caller could not read the file; the row must still
        // be usable rather than blank.
        let name = ProfileNaming.displayName(stem: "server", configText: nil)
        XCTAssertFalse(name.isEmpty)
        XCTAssertEqual(name, "Server")
    }

    func testEmptyStemDoesNotCrash() {
        XCTAssertEqual(ProfileNaming.displayName(stem: "", configText: nil), "")
    }

    // MARK: - Country code

    func testCountryCodeParsing() {
        XCTAssertEqual(WireGuardProfiles.countryCode("VPN-RO1-RO-229"), "RO")
        XCTAssertEqual(WireGuardProfiles.countryCode("VPN-DE1-DE-522"), "DE")
        XCTAssertNil(WireGuardProfiles.countryCode("server"))
        XCTAssertNil(WireGuardProfiles.countryCode("work"))
    }

    // MARK: - Flags

    func testFlagForKnownCountries() {
        XCTAssertEqual(ProfileNaming.flag("RO"), "🇷🇴")
        XCTAssertEqual(ProfileNaming.flag("de"), "🇩🇪")
        XCTAssertEqual(ProfileNaming.flag("TR"), "🇹🇷")
    }

    /// Anything malformed returns nil so the row shows no glyph instead of a
    /// broken placeholder.
    func testFlagRejectsMalformedCodes() {
        XCTAssertNil(ProfileNaming.flag(nil))
        XCTAssertNil(ProfileNaming.flag(""))
        XCTAssertNil(ProfileNaming.flag("R"))
        XCTAssertNil(ProfileNaming.flag("ROO"))
        XCTAssertNil(ProfileNaming.flag("12"))
        XCTAssertNil(ProfileNaming.flag("R1"))
    }

    /// Every ASCII letter pair must produce a two-scalar string, never trap.
    func testEveryLetterPairProducesATwoScalarFlag() {
        for first in UInt8(ascii: "A")...UInt8(ascii: "Z") {
            for second in UInt8(ascii: "A")...UInt8(ascii: "Z") {
                let code = String(UnicodeScalar(first)) + String(UnicodeScalar(second))
                let flag = ProfileNaming.flag(code)
                XCTAssertEqual(flag?.unicodeScalars.count, 2, "failed for \(code)")
            }
        }
    }

    // MARK: - Display name survives the wire

    func testProfileCarriesDisplayThroughCodable() throws {
        let profile = Profile(name: "VPN-RO1-RO-229", file: "/tmp/a.conf",
                              endpoint: "1.2.3.4:51820", host: "1.2.3.4",
                              country: "RO", display: "Bükreş", active: true)
        let text = JSON.encode(profile)
        let decoded = try XCTUnwrap(JSON.decode(Profile.self, from: text))
        XCTAssertEqual(decoded.display, "Bükreş")
        XCTAssertEqual(decoded.country, "RO")
        XCTAssertTrue(decoded.active)
    }

    /// An older helper on disk will not send `display`; decoding must survive.
    func testProfileDecodesWithoutDisplay() throws {
        let text = #"{"name":"x","file":"/tmp/x.conf","active":false}"#
        let decoded = try XCTUnwrap(JSON.decode(Profile.self, from: text))
        XCTAssertNil(decoded.display)
        XCTAssertNil(decoded.country)
    }
}
